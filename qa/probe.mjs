import { spawn } from 'node:child_process';
import playwright from '/home/claude/.npm-global/lib/node_modules/playwright/index.js';
const { chromium } = playwright;
const procs = [];
const run = (cwd, cmd, args, env = {}) => { const c = spawn(cmd, args, { cwd, env: { ...process.env, ...env }, stdio: ['ignore','pipe','pipe'] }); c.stdout.on('data',()=>{}); c.stderr.on('data',(d)=>process.stderr.write(`[srv] ${d}`)); procs.push(c); };
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const waitFor = async (url) => { for (let i=0;i<90;i++){ try { const r= await fetch(url); if(r.status<500) return true; } catch{} await sleep(500);} return false; };
run('/home/claude/tf/apps/api','node',['--import','tsx','src/server.ts'],{PORT:'4000',LOG_LEVEL:'silent'});
run('/home/claude/tf/apps/web','npx',['vite','--port','5173','--strictPort']);
await waitFor('http://localhost:4000/api/v1/healthz'); await waitFor('http://localhost:5173');
const browser = await chromium.launch({ args:['--no-sandbox'] });
const page = await browser.newPage({ viewport:{width:1400,height:900} });
const logs = [];
page.on('pageerror', e => logs.push('PAGEERROR: ' + e.message + '\n' + (e.stack||'').split('\n').slice(0,4).join('\n')));
page.on('console', m => { if (m.type()==='error') logs.push('CONSOLE: ' + m.text()); });
page.on('response', r => { if (r.url().includes('/api/') && !r.ok()) logs.push(`HTTP ${r.status()} ${r.url()}`); });
await page.goto('http://localhost:5173/login');
await page.fill('input[type=email]','ayesha@northwind.test');
await page.fill('input[type=password]','Password123!');
await page.click('button:has-text("Sign in")');
await page.waitForSelector('.project-card',{timeout:20000});
await page.click('.project-card:has-text("TaskForge Platform")');
await sleep(4000);
console.log('URL:', page.url());
console.log('--- body text (first 400 chars) ---');
console.log((await page.innerText('body')).slice(0,400));
console.log('--- logs ---');
console.log(logs.slice(0,12).join('\n') || '(none)');
await page.screenshot({ path:'/home/claude/tf/qa/shots/debug-board.png' });
await browser.close();
procs.forEach(p=>{try{p.kill('SIGKILL')}catch{}});
process.exit(0);
